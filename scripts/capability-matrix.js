#!/usr/bin/env node
'use strict'
// Writes .docs/PHASE2_CAPABILITY_MATRIX.md from the service's own operation registry and from
// src/server/sync/operationKinds.js, the table the cloud really routes by. No database is opened.
//   node scripts/capability-matrix.js
const path = require('path')
const fs = require('fs')
const { createService } = require('../src/server/app')
const { kindOf, cloudRoute } = require('../src/server/sync/operationKinds')

const NOTES = {
  'auth.setup': 'First-run setup happens once, in the shop; the cloud starts from the shop’s data',
  'auth.login':
    'Same username and password; needs «الدخول عبر الإنترنت»; a session belongs to the side that opened it',
  'auth.setPassword':
    'Choosing a first password from the internet comes with the security milestone',
  'auth.recover': 'The recovery code is used on the shop PC',
  'auth.changePassword':
    'The password is carried in memory only, never written to an operation record',
  'shifts.open':
    'The user’s shift, as today. Opened on both sides while apart: both are kept and listed',
  'shifts.close': 'One close per shift, as today',
  'pos.checkout':
    'Into the user’s open shift, as today. The same stock sold on both sides while apart goes negative and is listed',
  'products.create': 'The same barcode created on both sides is one product',
  'products.update': 'A stock edit is a movement and adds up',
  'productUnits.save': 'Automatic package prices are recalculated',
  'sales.returnItem':
    'Refund by the existing order: customer debt, store credit, then the open shift. The same line returned on both sides beyond what was sold is listed',
  'sales.returnEntire': 'As above',
  'clients.create': 'The same phone or code on two new customers is listed',
  'clients.delete': 'Kept and listed if the other side used the customer meanwhile',
  'clients.repay': 'Into the user’s shift or the treasury, by the existing rule',
  'suppliers.addPurchase':
    'Paid from the user’s shift or the treasury, by the existing rule. Purchase price: the latest purchase by its own date',
  'suppliers.repay':
    'From the user’s shift or the treasury, by the existing rule. Paid on both sides beyond what is owed: listed',
  'expenses.create': 'From the user’s shift or the treasury, by the existing rule',
  'momkn.add': 'Old till service, no longer on any screen',
  'momkn.delete': 'Old till service',
  'mobileMoney.add': 'Old till service',
  'mobileMoney.delete': 'Old till service',
  'treasury.record': 'The one treasury',
  'treasury.reverse': 'An entry is reversed once, as today',
  'supplierInvoices.reserve': 'The 30-minute reservation, taken in the shop',
  'supplierPayments.create': 'The cash leaves the user’s open shift, as today',
  'supplierPayments.reserve': 'The 5-minute reservation, taken in the shop',
  'users.create': 'The same username created on both sides is listed',
  'users.update': 'A disabled account is signed out on both sides',
  'system.reset': 'Also needs the two unlinked first',
  'settings.update': 'Printer and device settings stay with the device',
  'backup.restore': 'The restored side pauses until it has caught up from the other',
  'backup.export': 'Each side keeps its own copies',
  'discounts.save': 'Each sale keeps the discount it was sold with',
  'categories.delete': 'Kept and listed if the other side used it meanwhile',
  'measureKinds.delete': 'Kept and listed if the other side used it meanwhile'
}
const KIND = {
  read: 'View',
  add: 'Adds up',
  merge: 'Merged by field',
  state: 'State of a record',
  linked: 'Needs the connection',
  device: 'Per device'
}
const REACHABLE = {
  local: 'Answered by the cloud from its copy',
  shop: 'Carried out in the shop, by this operation',
  refused: 'Shop PC only'
}
const APART = {
  read: 'Shows what the cloud last received',
  add: 'Runs in the cloud; kept and added on reconnection',
  merge: 'Runs in the cloud; merged on reconnection',
  state: 'Runs in the cloud; listed if the shop changed the same record meanwhile',
  linked: 'Not available until the shop is reachable',
  device: 'Its own'
}

;(async () => {
  const svc = await createService({
    databaseUrl: 'postgres://nobody:nothing@127.0.0.1:1/none',
    secret: 'x'.repeat(40),
    logger: false
  })
  const rows = [...svc.operations.values()].map((o) => ({
    name: o.name,
    mod: o.name.split('.')[0],
    perm: o.public
      ? 'none (before sign-in)'
      : [].concat(o.permission || []).join(' + ') ||
        (o.anyPermission ? 'any of: ' + o.anyPermission.join(', ') : 'signed in'),
    kind: kindOf(o.name),
    route: cloudRoute(o.name)
  }))
  const count = (f) => rows.filter(f).length
  const out = []
  out.push('# Phase 2 capability matrix: every service operation')
  out.push('')
  out.push(
    'Written for the owner and the developer. Generated by `node scripts/capability-matrix.js` from the service’s own operation registry and from `src/server/sync/operationKinds.js`, the table the cloud routes by, so the list, the permissions and the column “While the shop is reachable” are exactly what the program does. The design is in [PHASE2_ARCHITECTURE.md](PHASE2_ARCHITECTURE.md).'
  )
  out.push('')
  out.push(
    `**${rows.length} operations, one behaviour.** Each has one definition and one permission, used by both ways in.`
  )
  out.push('')
  out.push(
    `- **While the shop is reachable (implemented, milestone 1):** the cloud answers ${count((r) => r.route === 'local')} itself (the reads, sign-in and sign-out), carries ${count((r) => r.route === 'shop')} to the shop where the operation’s own handler runs as the same user, and refuses ${count((r) => r.route === 'refused')} that belong to the shop PC.`
  )
  out.push(
    '- **While the shop is unreachable (milestone 3, not implemented yet):** the last column says what will happen, and the kind says how the two sides are brought together afterwards. Until then a change is refused with a clear message and nothing is queued.'
  )
  out.push('')
  out.push('| Kind | Operations | On reconnection |')
  out.push('| --- | --- | --- |')
  const k = (x) => count((r) => r.kind === x)
  out.push(`| View | ${k('read')} | – |`)
  out.push(
    `| Adds up (sale, return, payment, purchase, movement, shift) | ${k('add')} | Both sides’ records are kept and added; a broken limit is listed |`
  )
  out.push(
    `| Merged by field (product, price, customer, supplier, user, role, setting) | ${k('merge')} | Field by field; the same field changed on both sides keeps the shop’s value and is listed |`
  )
  out.push(
    `| State of a record (close, approve, reject, cancel, complete, reverse) | ${k('state')} | Taken as it is; if both sides changed the same record, the shop’s result stands and the case is listed |`
  )
  out.push(
    `| Needs the connection (barcode change, deleting a record, reset) | ${k('linked')} | Cannot happen apart |`
  )
  out.push(
    `| Per device (sessions, reservations, backup files, link) | ${k('device')} | Not synchronised |`
  )
  let mod = null
  for (const r of rows) {
    if (r.mod !== mod) {
      mod = r.mod
      out.push('')
      out.push(`## ${mod} (${count((x) => x.mod === mod)})`)
      out.push('')
      out.push(
        '| Operation | Permission | Kind | While the shop is reachable | While it is unreachable | Note |'
      )
      out.push('| --- | --- | --- | --- | --- | --- |')
    }
    out.push(
      `| \`${r.name}\` | ${r.perm} | ${KIND[r.kind]} | ${REACHABLE[r.route]} | ${r.route === 'refused' ? 'Shop PC only' : APART[r.kind]} | ${NOTES[r.name] || ''} |`
    )
  }
  out.push('')
  const file = path.join(__dirname, '..', '.docs', 'PHASE2_CAPABILITY_MATRIX.md')
  fs.writeFileSync(file, out.join('\n'))
  console.log(`written ${file} (${rows.length} operations)`)
  await svc.app.close().catch(() => {})
  process.exit(0)
})().catch((e) => {
  console.error(e.message)
  process.exit(1)
})
