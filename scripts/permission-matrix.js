'use strict'
// The permission matrix (ROLE-02, D-075), generated from the code: the permission catalogue, the
// built-in roles' defaults and every service operation with the permission it requires. The file
// .docs/PERMISSION_MATRIX.md is this script's output; tests/service/permissionsAudit.test.js fails
// when it is out of date. Regenerate with:  node scripts/permission-matrix.js
const fs = require('fs')
const path = require('path')
const { PERMISSIONS, SYSTEM_ROLES } = require('../src/server/auth/permissions')
const { createService } = require('../src/server/app')

const OUT = path.join(__dirname, '..', '.docs', 'PERMISSION_MATRIX.md')

// Operations every signed-in user may call, and why; and those before signing in.
const SIGNED_IN = {
  'auth.logout': 'end the own session',
  'auth.me': 'the own account and permissions',
  'auth.changePassword': 'the own password (old password required)',
  'auth.newRecoveryCode': 'the own recovery code (password required)',
  'settings.public':
    'display settings only: store name and address, logo, receipt paper, reminders',
  'sync.state': 'two yes/no flags: linked to the cloud, recovery pending',
  'measureKinds.list': 'names and decimals of the measurement kinds'
}
const PUBLIC = {
  'auth.status': 'is the store set up (sign-in screen)',
  'auth.setup': 'first owner account, only while no user exists',
  'auth.login': 'sign in (rate-limited)',
  'auth.setPassword': 'first password with the one-time code',
  'auth.recover': 'reset with the recovery code'
}

/** Every registered operation without connecting to a database. */
async function listOperations() {
  const svc = await createService({
    databaseUrl: 'postgres://matrix:matrix@127.0.0.1:1/none',
    secret: 'permission-matrix-listing-only-not-a-real-secret',
    logger: false
  })
  const ops = [...svc.operations.values()].map((o) => ({
    name: o.name,
    all: o.permission ? [].concat(o.permission) : [],
    any: o.anyPermission || [],
    public: !!o.public
  }))
  await svc.app.close().catch(() => {})
  await svc.pool.end().catch(() => {})
  return ops.sort((a, b) => a.name.localeCompare(b.name))
}

async function buildMatrix() {
  const ops = await listOperations()
  const roles = SYSTEM_ROLES
  const yes = (r, k) => (r.permissions.includes(k) ? '✓' : '')
  const lines = []
  lines.push('# Permission matrix')
  lines.push('')
  lines.push(
    'Generated by `node scripts/permission-matrix.js` from the code (ROLE-02, D-075); do not edit by hand. A test fails when this file is out of date.'
  )
  lines.push('')
  lines.push(
    'Every permission is checked by the service on every request, before the request is read; hiding a button is only a convenience. Each role below is a default: an administrator changes any role in «الأدوار والصلاحيات», and only grants permissions they hold themselves.'
  )
  lines.push('')
  lines.push('## Permissions and the built-in roles')
  lines.push('')
  lines.push(`| Permission | Name | ${roles.map((r) => r.name).join(' | ')} |`)
  lines.push(`| --- | --- | ${roles.map(() => ':-:').join(' | ')} |`)
  for (const p of PERMISSIONS)
    lines.push(
      `| \`${p.key}\` | ${p.label}${p.hidden ? ' (hidden in the roles screen)' : ''} | ${roles.map((r) => yes(r, p.key)).join(' | ')} |`
    )
  lines.push('')
  lines.push('## Operations and the permission each requires')
  lines.push('')
  lines.push('"all of" = every listed permission; "any of" = at least one.')
  lines.push('')
  lines.push('| Operation | Requires |')
  lines.push('| --- | --- |')
  for (const o of ops) {
    let need
    if (o.public) need = `before sign-in: ${PUBLIC[o.name] || '(no reason recorded)'}`
    else if (!o.all.length && !o.any.length)
      need = `any signed-in user: ${SIGNED_IN[o.name] || '(no reason recorded)'}`
    else
      need = [
        o.all.length ? `all of ${o.all.map((p) => `\`${p}\``).join(', ')}` : '',
        o.any.length ? `any of ${o.any.map((p) => `\`${p}\``).join(', ')}` : ''
      ]
        .filter(Boolean)
        .join('; ')
    lines.push(`| \`${o.name}\` | ${need} |`)
  }
  lines.push('')
  lines.push('## Checks inside operations')
  lines.push('')
  lines.push(
    'Some operations decide more inside, on top of the permission above: a cashier sees and cancels only the preliminary invoices they recorded; expected amounts of an open shift need `shifts.view_expected` (blind close, D-073); recording money directly in the treasury needs `treasury.manage`; an opening balance on a new supplier needs `suppliers.opening`; costs are hidden without `products.view_cost`; a user can be given only a role whose permissions the administrator holds.'
  )
  lines.push('')
  // Formatted like every other document (Prettier), so the file and the test compare exactly.
  const prettier = await import('prettier')
  const options = (await prettier.resolveConfig(OUT)) || {}
  return prettier.format(lines.join('\n'), { ...options, parser: 'markdown' })
}

module.exports = { buildMatrix, listOperations, SIGNED_IN, PUBLIC, OUT }

if (require.main === module)
  buildMatrix().then((md) => {
    fs.writeFileSync(OUT, md)
    console.log(`written ${OUT}`)
  })
