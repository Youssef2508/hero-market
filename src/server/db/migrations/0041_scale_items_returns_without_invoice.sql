-- 0041 – Scale items keep their own codes (D-117) and returns without an invoice (D-116).

-- ── Scale items (D-117) ──────────────────────────────────────────────────────────────────────
-- A product marked «صنف ميزان» is found from a scale label by its own code: the label's item-code
-- digits are matched to the code without its leading zeros, so 1, 01 and 001 would all be the
-- same scale item. scale_key is that comparison key (NULL when the product is not a scale item);
-- the code itself is never changed. At most one product per key: two scale items that a label
-- could not tell apart are refused by the service and, as a last guard, here. Deferred to the end
-- of the transaction, so one synchronised batch that moves the key from one product to another
-- (one switched off, the other on) is applied whole.
ALTER TABLE products ADD COLUMN scale_item boolean NOT NULL DEFAULT false;
ALTER TABLE products ADD COLUMN scale_key text;
ALTER TABLE products ADD CONSTRAINT products_scale_key_unique UNIQUE (scale_key) DEFERRABLE INITIALLY DEFERRED;
ALTER TABLE products ADD CONSTRAINT products_scale_key_set
  CHECK ((scale_item AND scale_key IS NOT NULL) OR (NOT scale_item AND scale_key IS NULL));

-- ── Returns without an invoice (D-116) ───────────────────────────────────────────────────────
-- A trusted customer brings goods back without the receipt (permission sales.return_without_invoice).
-- Its own document: never a sale_returns row, never an invoice number it does not have. The goods
-- go back into stock ('customer_return' movements) and the refund leaves the cashier's drawer as a
-- 'refund' movement of the open shift.
CREATE TABLE customer_returns (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shift_id      integer NOT NULL REFERENCES shifts(id),
  user_id       integer REFERENCES users(id),
  username      text,
  client_id     integer REFERENCES clients(id),
  client_name   text,
  reason        text NOT NULL CHECK (length(trim(reason)) > 0),
  total         numeric(14, 2) NOT NULL CHECK (total > 0),
  method        text NOT NULL DEFAULT 'cash',
  ledger_id     integer,                     -- the drawer movement that paid it (safe_ledger.id)
  client_ref    text NOT NULL UNIQUE CHECK (length(client_ref) <= 120),
  created_at    timestamp NOT NULL DEFAULT LOCALTIMESTAMP(0)
);
CREATE INDEX customer_returns_shift ON customer_returns (shift_id);
CREATE INDEX customer_returns_time ON customer_returns (created_at DESC, id DESC);

-- Each product brought back, with the price applied: the product's selling price at the time,
-- kept here so a later price change never changes the return.
CREATE TABLE customer_return_items (
  id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  return_id       integer NOT NULL REFERENCES customer_returns(id) ON DELETE CASCADE,
  product_barcode text NOT NULL REFERENCES products(barcode) ON UPDATE CASCADE,
  product_name    text NOT NULL,
  unit_id         integer,
  unit_name       text,
  unit_factor     numeric(14, 4) NOT NULL DEFAULT 1,
  quantity        numeric(14, 3) NOT NULL CHECK (quantity > 0),
  unit_price      numeric(14, 2) NOT NULL CHECK (unit_price >= 0),
  total           numeric(14, 2) NOT NULL,
  movement_id     bigint                       -- the stock movement it posted
);
CREATE INDEX customer_return_items_return ON customer_return_items (return_id);
CREATE INDEX customer_return_items_product ON customer_return_items (product_barcode);

INSERT INTO sync_tables (table_name, key_column) VALUES ('customer_returns', 'id'), ('customer_return_items', 'id');
CREATE TRIGGER zz_sync_capture AFTER INSERT OR UPDATE OR DELETE ON customer_returns
  FOR EACH ROW EXECUTE FUNCTION hm_sync_capture('id');
CREATE TRIGGER zz_sync_capture AFTER INSERT OR UPDATE OR DELETE ON customer_return_items
  FOR EACH ROW EXECUTE FUNCTION hm_sync_capture('id');

ALTER TABLE stock_movements
  DROP CONSTRAINT stock_movements_kind_check,
  ADD CONSTRAINT stock_movements_kind_check
    CHECK (kind IN ('opening', 'sale', 'return', 'customer_return', 'purchase', 'purchase_return',
                    'purchase_correction', 'adjustment', 'count', 'damaged', 'damaged_reversal'));
