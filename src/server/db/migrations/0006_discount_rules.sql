-- Administrator-managed automatic discounts (owner decision 2026-10-15).
--
-- Cashiers have no discount authority: manual invoice discounts are no longer accepted from any
-- operator. The administrator defines rules in advance; checkout evaluates them on the server:
--   * product rules: a percentage, or an amount per base unit, off one product;
--   * cart rules: a percentage or a fixed amount off the whole cart when the total after product
--     discounts reaches a threshold (tiers: the best qualifying rule applies).
-- Each sale keeps the discounts it received (sale_discounts) and each line keeps its own share, so
-- later rule or price changes never alter history, receipts, returns or reports.

CREATE TABLE discount_rules (
  id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name            text NOT NULL CHECK (length(trim(name)) > 0),
  scope           text NOT NULL CHECK (scope IN ('product', 'cart')),
  product_barcode text REFERENCES products(barcode) ON UPDATE CASCADE,
  value_type      text NOT NULL CHECK (value_type IN ('percent', 'amount')),
  value           numeric NOT NULL CHECK (value > 0),
  min_total       numeric NOT NULL DEFAULT 0 CHECK (min_total >= 0),   -- cart rules: threshold (EGP)
  starts_at       timestamp,                                            -- NULL: no start limit
  ends_at         timestamp,                                            -- NULL: no end limit
  is_active       boolean NOT NULL DEFAULT true,
  version         integer NOT NULL DEFAULT 1,
  created_by      integer,
  created_at      timestamp NOT NULL DEFAULT LOCALTIMESTAMP(0),
  updated_by      integer,
  updated_at      timestamp,
  CHECK ((scope = 'product') = (product_barcode IS NOT NULL)),
  CHECK (value_type <> 'percent' OR value <= 100),
  CHECK (ends_at IS NULL OR starts_at IS NULL OR ends_at > starts_at)
);
CREATE INDEX idx_discount_rules_product ON discount_rules(product_barcode) WHERE is_active;

CREATE TABLE sale_discounts (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sale_id    integer NOT NULL REFERENCES sales(id),
  rule_id    integer REFERENCES discount_rules(id),
  scope      text NOT NULL,
  name       text NOT NULL,          -- snapshot of the rule name
  value_type text NOT NULL,
  value      numeric NOT NULL,
  amount     numeric NOT NULL        -- EGP actually deducted on this sale
);
CREATE INDEX idx_sale_discounts_sale ON sale_discounts(sale_id);

-- Per-line shares: total_price stays quantity × unit price (gross); the line's net is
-- total_price − line_discount − cart_discount.
ALTER TABLE sale_items
  ADD COLUMN line_discount numeric NOT NULL DEFAULT 0 CHECK (line_discount >= 0),
  ADD COLUMN cart_discount numeric NOT NULL DEFAULT 0 CHECK (cart_discount >= 0);

-- 1 = legacy pricing (one invoice-level discount); 2 = rule-based pricing with per-line shares.
ALTER TABLE sales ADD COLUMN pricing_version smallint NOT NULL DEFAULT 1;

-- The manual discount permission no longer exists.
DELETE FROM role_permissions WHERE permission = 'pos.discount';
DELETE FROM permission_catalog WHERE key = 'pos.discount';
