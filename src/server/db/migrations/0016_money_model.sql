-- 0016 – Money model (owner feedback phase D, 1.5.0; .docs/FINANCIAL_RECONCILIATION.md, D-062).
--
-- Adds; removes and rewrites nothing:
--   1. safe_ledger.method: which payment method a shift movement uses. Every existing row was drawer
--      cash, which is the default, so no existing figure changes.
--   2. treasury_ledger: the store's cash outside the drawers. Immutable rows (corrections are new
--      rows). It starts empty: older shifts are not replayed into it (that would invent a balance).
--   3. shift_closings: the saved close of a shift (expected, actual and variance per method and the
--      printed report), so a reprint shows exactly what was confirmed. Older closes keep their
--      figures in shifts; they have no snapshot.
--   4. expense_categories, and on expenses: who created it, its category, where it was paid from and
--      the ledger row it posted. created_by is filled from the shift's cashier (the only one who
--      could record it before 1.5.0); category_id from the stored category name.
--   5. sale_payment_corrections: the record of every change of a sale's payment method.
--
-- Classification (spec §8): schema + data (backfill of new columns from existing rows only).
-- Rollback: restore the verified copy taken by the installer before this migration (Case B).

-- 1. Payment method of each shift movement.
ALTER TABLE safe_ledger
  ADD COLUMN method text NOT NULL DEFAULT 'cash'
    CHECK (method IN ('cash', 'visa', 'wallet', 'instapay'));

-- 2. Treasury.
CREATE TABLE treasury_ledger (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind        text NOT NULL CHECK (kind IN ('opening_float', 'shift_close', 'deposit', 'withdrawal',
                'expense', 'customer_payment', 'supplier_payment', 'adjustment', 'reversal')),
  -- + into the treasury, − out of it.
  amount      numeric(14, 2) NOT NULL CHECK (amount <> 0),
  shift_id    integer REFERENCES shifts(id),
  ref_type    text CHECK (ref_type IS NULL OR ref_type IN ('shift', 'expense', 'client', 'supplier')),
  ref_id      integer,
  reverses_id integer UNIQUE REFERENCES treasury_ledger(id),
  description text NOT NULL CHECK (length(description) BETWEEN 1 AND 300),
  reason      text CHECK (reason IS NULL OR length(reason) <= 300),
  user_id     integer REFERENCES users(id),
  username    text,
  idem_key    text UNIQUE CHECK (idem_key IS NULL OR length(idem_key) <= 120),
  created_at  timestamp NOT NULL DEFAULT LOCALTIMESTAMP(0)
);
CREATE INDEX idx_treasury_created ON treasury_ledger (created_at, id);
CREATE INDEX idx_treasury_shift ON treasury_ledger (shift_id) WHERE shift_id IS NOT NULL;

-- Posted money is never edited or removed (TREAS-01); only a restore, a reset or a recovery from
-- the cloud replaces it (the same exemptions as hm_require_open_shift, 0011).
CREATE FUNCTION hm_immutable_money() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF current_setting('hm.bulk_load', true) = 'on' OR current_setting('hm.ledger_rebuild', true) = 'on' THEN
    RETURN COALESCE(NEW, OLD);
  END IF;
  RAISE EXCEPTION 'لا يمكن تعديل أو حذف حركة مالية مسجلة؛ سجّل حركة عكسية بسبب واضح.'
    USING ERRCODE = 'P0001';
END $$;
CREATE TRIGGER immutable_money BEFORE UPDATE OR DELETE ON treasury_ledger
  FOR EACH ROW EXECUTE FUNCTION hm_immutable_money();

-- 3. Saved shift closes.
CREATE TABLE shift_closings (
  shift_id          integer PRIMARY KEY REFERENCES shifts(id),
  closed_at         timestamp NOT NULL,
  closed_by         integer REFERENCES users(id),
  client_ref        text UNIQUE CHECK (client_ref IS NULL OR length(client_ref) <= 120),
  expected          jsonb NOT NULL,
  actual            jsonb NOT NULL,
  variance          jsonb NOT NULL,
  report            jsonb NOT NULL,
  treasury_entry_id integer REFERENCES treasury_ledger(id)
);
CREATE TRIGGER immutable_money BEFORE UPDATE OR DELETE ON shift_closings
  FOR EACH ROW EXECUTE FUNCTION hm_immutable_money();

-- 4. Expenses: categories, creator, destination.
CREATE TABLE expense_categories (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        text NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 60),
  is_active   boolean NOT NULL DEFAULT true,
  sort_order  integer NOT NULL DEFAULT 0,
  created_at  timestamp NOT NULL DEFAULT LOCALTIMESTAMP(0),
  updated_at  timestamp
);
CREATE UNIQUE INDEX expense_categories_name_key ON expense_categories (lower(btrim(name)));

-- The categories the screen offered until 1.4.0, then any other name already used.
INSERT INTO expense_categories (name, sort_order)
SELECT name, ord FROM (VALUES
  ('عام', 1), ('صيانة', 2), ('إيجار', 3), ('كهرباء', 4), ('أجور', 5), ('بضائع', 6), ('توصيل', 7)
) AS d(name, ord);
INSERT INTO expense_categories (name, sort_order)
SELECT name, 100 + row_number() OVER (ORDER BY name)::int
  FROM (SELECT DISTINCT ON (lower(btrim(category))) btrim(category) AS name
          FROM expenses
         WHERE length(btrim(COALESCE(category, ''))) BETWEEN 1 AND 60
         ORDER BY lower(btrim(category)), btrim(category)) e
 WHERE NOT EXISTS (SELECT 1 FROM expense_categories c WHERE lower(btrim(c.name)) = lower(e.name));

ALTER TABLE expenses
  ADD COLUMN created_by        integer REFERENCES users(id),
  ADD COLUMN category_id       integer REFERENCES expense_categories(id) ON DELETE RESTRICT,
  ADD COLUMN destination       text NOT NULL DEFAULT 'shift' CHECK (destination IN ('shift', 'treasury')),
  ADD COLUMN ledger_id         integer,
  ADD COLUMN treasury_entry_id integer REFERENCES treasury_ledger(id);
CREATE INDEX idx_expenses_created_by ON expenses (created_by, id);

-- Backfill touches expenses of closed shifts on purpose (new bookkeeping columns, no money).
SELECT set_config('hm.bulk_load', 'on', true);
UPDATE expenses x SET created_by = s.user_id FROM shifts s WHERE s.id = x.shift_id;
UPDATE expenses x SET category_id = c.id
  FROM expense_categories c WHERE lower(btrim(x.category)) = lower(btrim(c.name));
SELECT set_config('hm.bulk_load', 'off', true);

-- 5. Payment method corrections (PAY-02).
CREATE TABLE sale_payment_corrections (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sale_id      integer NOT NULL REFERENCES sales(id),
  shift_id     integer NOT NULL REFERENCES shifts(id),
  from_type    text NOT NULL,
  to_type      text NOT NULL,
  amount       numeric(14, 2) NOT NULL,
  reason       text NOT NULL CHECK (length(btrim(reason)) BETWEEN 3 AND 300),
  user_id      integer REFERENCES users(id),
  username     text,
  client_ref   text UNIQUE CHECK (client_ref IS NULL OR length(client_ref) <= 120),
  created_at   timestamp NOT NULL DEFAULT LOCALTIMESTAMP(0)
);
CREATE INDEX idx_payment_corrections_sale ON sale_payment_corrections (sale_id);
CREATE TRIGGER immutable_money BEFORE UPDATE OR DELETE ON sale_payment_corrections
  FOR EACH ROW EXECUTE FUNCTION hm_immutable_money();

-- Synchronisation to the owner's cloud copy (0009), like every other business table.
INSERT INTO sync_tables (table_name, key_column) VALUES
  ('treasury_ledger', 'id'), ('shift_closings', 'shift_id'), ('expense_categories', 'id'),
  ('sale_payment_corrections', 'id');
CREATE TRIGGER zz_sync_capture AFTER INSERT OR UPDATE OR DELETE ON treasury_ledger
  FOR EACH ROW EXECUTE FUNCTION hm_sync_capture('id');
CREATE TRIGGER zz_sync_capture AFTER INSERT OR UPDATE OR DELETE ON shift_closings
  FOR EACH ROW EXECUTE FUNCTION hm_sync_capture('shift_id');
CREATE TRIGGER zz_sync_capture AFTER INSERT OR UPDATE OR DELETE ON expense_categories
  FOR EACH ROW EXECUTE FUNCTION hm_sync_capture('id');
CREATE TRIGGER zz_sync_capture AFTER INSERT OR UPDATE OR DELETE ON sale_payment_corrections
  FOR EACH ROW EXECUTE FUNCTION hm_sync_capture('id');
