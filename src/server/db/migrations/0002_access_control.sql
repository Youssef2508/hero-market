-- 0002 – Access control, sessions, idempotent checkout, receipt templates.
-- Additive only: legacy tables gain nullable columns; no legacy value is changed here.

CREATE TABLE roles (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  key          text UNIQUE,                       -- stable key for built-in roles (super_admin, manager, …); NULL for custom roles
  name         text NOT NULL UNIQUE,
  description  text,
  is_system    boolean NOT NULL DEFAULT false,    -- built-in: cannot be deleted
  is_protected boolean NOT NULL DEFAULT false,    -- permissions fixed (super administrator)
  created_at   timestamp NOT NULL DEFAULT LOCALTIMESTAMP(0),
  updated_at   timestamp
);

CREATE TABLE role_permissions (
  role_id    integer NOT NULL REFERENCES roles(id) ON DELETE CASCADE,
  permission text NOT NULL,
  PRIMARY KEY (role_id, permission)
);

ALTER TABLE users
  ADD COLUMN role_id    integer REFERENCES roles(id),
  ADD COLUMN pin_lookup text,          -- HMAC-SHA256(server secret, PIN): unique lookup key
  ADD COLUMN pin_hash   text,          -- scrypt$N$r$p$salt$hash
  ADD COLUMN is_active  boolean NOT NULL DEFAULT true,
  ADD COLUMN created_at timestamp,
  ADD COLUMN updated_at timestamp;
CREATE UNIQUE INDEX users_pin_lookup_key ON users(pin_lookup) WHERE pin_lookup IS NOT NULL;

CREATE TABLE sessions (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  token_hash   text NOT NULL UNIQUE,    -- SHA-256 of the bearer token; the token itself is never stored
  user_id      integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  terminal     text,
  created_at   timestamp NOT NULL DEFAULT LOCALTIMESTAMP(0),
  last_seen_at timestamp NOT NULL DEFAULT LOCALTIMESTAMP(0),
  expires_at   timestamp NOT NULL,
  revoked_at   timestamp
);
CREATE INDEX idx_sessions_user ON sessions(user_id);

-- Idempotent checkout: the terminal sends a unique key per sale; a retry returns the same sale.
ALTER TABLE sales ADD COLUMN client_ref text;
CREATE UNIQUE INDEX sales_client_ref_key ON sales(client_ref) WHERE client_ref IS NOT NULL;

CREATE TABLE receipt_templates (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       text NOT NULL UNIQUE,
  paper      text NOT NULL DEFAULT '80mm' CHECK (paper IN ('58mm', '80mm', 'A4')),
  config     jsonb NOT NULL,
  is_active  boolean NOT NULL DEFAULT false,
  created_at timestamp NOT NULL DEFAULT LOCALTIMESTAMP(0),
  updated_at timestamp
);
-- At most one active template per paper size.
CREATE UNIQUE INDEX receipt_templates_active_per_paper ON receipt_templates(paper) WHERE is_active;
