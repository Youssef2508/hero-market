-- 0013 – Product categories and category browsing at the till (1.4.0).
--
-- One primary category per product (the simplest model that fits a supermarket till: every
-- product appears in exactly one place when browsing). Products without a category stay sellable
-- and appear under "بدون تصنيف". Categories are deactivated rather than deleted; a category can
-- only be deleted while it holds no products, so no product is ever lost with its category.
--
-- The categories already present in the data (the free-text products.category imported from
-- version 1.3) become real categories – nothing is invented. products.category keeps mirroring the
-- category name for older readers (reports, exports).
--
-- Products can be stopped from sale (is_active = false): they disappear from search and browsing
-- and checkout refuses them; their history stays.
--
-- catalog_state.version changes whenever something the till shows while browsing changes (names,
-- prices, units, categories, active status), so a till can keep the catalogue in memory and only
-- reload after a real change. Stock movements do not change it.

CREATE TABLE categories (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name         text NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 60),
  description  text CHECK (description IS NULL OR length(description) <= 200),
  sort_order   integer NOT NULL DEFAULT 0,
  is_active    boolean NOT NULL DEFAULT true,
  created_at   timestamp NOT NULL DEFAULT LOCALTIMESTAMP(0),
  updated_at   timestamp
);
CREATE UNIQUE INDEX categories_name_key ON categories (lower(btrim(name)));

ALTER TABLE products
  ADD COLUMN category_id integer REFERENCES categories(id) ON DELETE RESTRICT,
  ADD COLUMN is_active   boolean NOT NULL DEFAULT true;
CREATE INDEX idx_products_category ON products (category_id, name) WHERE is_active;

INSERT INTO sync_tables (table_name, key_column) VALUES ('categories', 'id');
CREATE TRIGGER zz_sync_capture AFTER INSERT OR UPDATE OR DELETE ON categories
  FOR EACH ROW EXECUTE FUNCTION hm_sync_capture('id');

-- Existing classifications.
INSERT INTO categories (name, sort_order)
SELECT name, row_number() OVER (ORDER BY name)::int
  FROM (SELECT DISTINCT ON (lower(btrim(category))) btrim(category) AS name
          FROM products
         WHERE length(btrim(COALESCE(category, ''))) BETWEEN 1 AND 60
         ORDER BY lower(btrim(category)), btrim(category)) d;
-- Assigning categories is not a stock change: the stock guard (0004) is not involved.
UPDATE products p SET category_id = c.id
  FROM categories c
 WHERE lower(btrim(p.category)) = lower(btrim(c.name));

-- Catalogue version for the tills' browsing cache.
CREATE TABLE catalog_state (
  id          boolean PRIMARY KEY DEFAULT true CHECK (id),
  version     bigint NOT NULL DEFAULT 1,
  changed_at  timestamp NOT NULL DEFAULT LOCALTIMESTAMP(0)
);
INSERT INTO catalog_state DEFAULT VALUES;

CREATE FUNCTION hm_bump_catalog() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  UPDATE catalog_state SET version = version + 1, changed_at = LOCALTIMESTAMP(0);
  RETURN NULL;
END $$;

CREATE TRIGGER bump_catalog AFTER INSERT OR DELETE OR UPDATE ON categories
  FOR EACH STATEMENT EXECUTE FUNCTION hm_bump_catalog();
CREATE TRIGGER bump_catalog_ins AFTER INSERT OR DELETE ON products
  FOR EACH STATEMENT EXECUTE FUNCTION hm_bump_catalog();
CREATE TRIGGER bump_catalog_upd AFTER UPDATE ON products
  FOR EACH ROW WHEN (
    OLD.barcode IS DISTINCT FROM NEW.barcode OR OLD.name IS DISTINCT FROM NEW.name
    OR OLD.retail_price IS DISTINCT FROM NEW.retail_price OR OLD.unit IS DISTINCT FROM NEW.unit
    OR OLD.unit_kind IS DISTINCT FROM NEW.unit_kind OR OLD.category_id IS DISTINCT FROM NEW.category_id
    OR OLD.is_active IS DISTINCT FROM NEW.is_active)
  EXECUTE FUNCTION hm_bump_catalog();
CREATE TRIGGER bump_catalog AFTER INSERT OR DELETE OR UPDATE ON product_units
  FOR EACH STATEMENT EXECUTE FUNCTION hm_bump_catalog();
