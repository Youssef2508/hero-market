-- 0033 – The cloud works while the shop is unreachable, and the two come together afterwards
-- (Phase 2 milestone 3, D-103). Nothing here changes existing business data.
--
--   1. Every captured update also keeps the row as it was before (prev_data), so the receiving
--      side can tell which fields the sender changed and merge field by field.
--   2. A change written while merging the other side's changes is marked as an echo: it is sent
--      to the cloud's record of the shop but never applied there a second time.
--   3. sync_received: which of the other side's changes were applied here (each one exactly once).
--   4. Two number books: the shop numbers from 1, the cloud from 1,000,000,001 (sync_state.id_floor),
--      so records made apart can never share a number.
--   5. sync_attention: what a person must look at after the two came together. Written by the
--      shop only (it holds both sides' records), synchronised to the cloud.
--   6. While merging, the rule "one open shift per user" lets the other side's shift in (both are
--      kept and listed), as the other selling-time guards already do under hm.ledger_rebuild.

ALTER TABLE sync_outbox
  ADD COLUMN prev_data jsonb,
  ADD COLUMN echo boolean NOT NULL DEFAULT false;

ALTER TABLE sync_state ADD COLUMN id_floor bigint NOT NULL DEFAULT 0;

CREATE TABLE sync_received (
  origin      uuid NOT NULL,          -- the sending database
  outbox_id   bigint NOT NULL,        -- its change number
  received_at timestamp NOT NULL DEFAULT LOCALTIMESTAMP(0),
  PRIMARY KEY (origin, outbox_id)
);

CREATE TABLE sync_attention (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind         text NOT NULL,         -- conflict, stock_negative, overpaid, returned_twice, ...
  table_name   text,
  row_key      text,
  detail       jsonb NOT NULL DEFAULT '{}'::jsonb,
  status       text NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'resolved')),
  created_at   timestamp NOT NULL DEFAULT LOCALTIMESTAMP(0),
  resolved_by  integer,
  resolved_at  timestamp,
  note         text
);
CREATE INDEX sync_attention_open ON sync_attention (id) WHERE status = 'open';
INSERT INTO sync_tables (table_name, key_column) VALUES ('sync_attention', 'id');
CREATE TRIGGER zz_sync_capture AFTER INSERT OR UPDATE OR DELETE ON sync_attention
  FOR EACH ROW EXECUTE FUNCTION hm_sync_capture('id');

DROP FUNCTION hm_sync_enqueue(text, text, text, jsonb);
CREATE FUNCTION hm_sync_enqueue(tbl text, key text, op text, r jsonb, prev jsonb DEFAULT NULL)
RETURNS bigint LANGUAGE plpgsql AS $$
DECLARE v bigint := nextval('sync_row_version');
BEGIN
  INSERT INTO sync_outbox (table_name, pk, op, row_data, prev_data, version, echo)
  VALUES (tbl, key, op,
          CASE WHEN op = 'delete' THEN NULL ELSE hm_sync_row(tbl, r) END,
          CASE WHEN prev IS NULL THEN NULL ELSE hm_sync_row(tbl, prev) END,
          v, COALESCE(current_setting('hm.sync_capture', true) = 'echo', false));
  INSERT INTO sync_row_versions (table_name, pk, version, deleted) VALUES (tbl, key, v, op = 'delete')
  ON CONFLICT (table_name, pk) DO UPDATE SET version = EXCLUDED.version, deleted = EXCLUDED.deleted;
  PERFORM pg_notify('hm_sync_outbox', '');
  RETURN v;
END $$;

CREATE OR REPLACE FUNCTION hm_sync_capture() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
  k text := TG_ARGV[0];
  newkey text;
  oldkey text;
BEGIN
  -- Administrative bulk work (backup restore) turns capture off; merging the other side's
  -- changes captures them as echoes ('echo').
  IF current_setting('hm.sync_capture', true) = 'off' THEN
    RETURN NULL;
  END IF;
  IF TG_OP = 'DELETE' THEN
    PERFORM hm_sync_enqueue(TG_TABLE_NAME, hm_sync_key(k, to_jsonb(OLD)), 'delete', NULL);
    RETURN NULL;
  END IF;
  newkey := hm_sync_key(k, to_jsonb(NEW));
  IF TG_OP = 'UPDATE' THEN
    oldkey := hm_sync_key(k, to_jsonb(OLD));
    IF oldkey IS DISTINCT FROM newkey THEN
      -- The key itself changed (e.g. a product's barcode): the old key is gone.
      PERFORM hm_sync_enqueue(TG_TABLE_NAME, oldkey, 'delete', NULL);
      PERFORM hm_sync_enqueue(TG_TABLE_NAME, newkey, 'upsert', to_jsonb(NEW));
      RETURN NULL;
    ELSIF to_jsonb(OLD) = to_jsonb(NEW) THEN
      RETURN NULL; -- nothing changed
    END IF;
    PERFORM hm_sync_enqueue(TG_TABLE_NAME, newkey, 'upsert', to_jsonb(NEW), to_jsonb(OLD));
    RETURN NULL;
  END IF;
  PERFORM hm_sync_enqueue(TG_TABLE_NAME, newkey, 'upsert', to_jsonb(NEW));
  RETURN NULL;
END $$;

CREATE OR REPLACE FUNCTION hm_prevent_multiple_open_shifts() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  -- Merging the other side's records: its shift is a fact that already happened (D-103).
  IF current_setting('hm.ledger_rebuild', true) = 'on' THEN
    RETURN NEW;
  END IF;
  IF NEW.status = 'open' THEN
    PERFORM pg_advisory_xact_lock(hashtext('hm-open-shift:' || NEW.user_id));
    IF EXISTS (SELECT 1 FROM shifts WHERE user_id = NEW.user_id AND status = 'open') THEN
      RAISE EXCEPTION 'خطأ: يوجد وردية مفتوحة بالفعل لهذا المستخدم.' USING ERRCODE = 'P0001';
    END IF;
  END IF;
  RETURN NEW;
END $$;

-- Keep every number counter of this database inside its own book: [floor + 1, floor + 10^9).
-- The shop's floor is 0; the cloud's is 1,000,000,000. Received records from the other book never
-- move a counter.
CREATE FUNCTION hm_keep_id_range() RETURNS void LANGUAGE plpgsql AS $$
DECLARE
  f bigint := (SELECT id_floor FROM sync_state);
  t record;
  top bigint;
  cur bigint;
BEGIN
  -- Every sequence that numbers an "id" column (identity or serial) of a table in this schema.
  FOR t IN
    SELECT c.relname AS tbl, s.oid::regclass::text AS seq
      FROM pg_class s
      JOIN pg_depend d ON d.objid = s.oid AND d.classid = 'pg_class'::regclass AND d.deptype IN ('a', 'i')
      JOIN pg_class c ON c.oid = d.refobjid
      JOIN pg_attribute a ON a.attrelid = c.oid AND a.attnum = d.refobjsubid
     WHERE s.relkind = 'S' AND a.attname = 'id' AND c.relnamespace = 'public'::regnamespace
  LOOP
    EXECUTE format('SELECT COALESCE(max(id), 0) FROM %I WHERE id > $1 AND id < $2', t.tbl)
      INTO top USING f, f + 1000000000;
    -- A counter already ahead inside its book stays where it is (numbers are never reused).
    EXECUTE format('SELECT CASE WHEN is_called THEN last_value ELSE last_value - 1 END FROM %s', t.seq)
      INTO cur;
    IF cur > f AND cur < f + 1000000000 THEN
      top := GREATEST(top, cur);
    END IF;
    PERFORM setval(t.seq, GREATEST(top, f + 1), top > f);
  END LOOP;
END $$;
