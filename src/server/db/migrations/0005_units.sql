-- Stage 4, phase 2: units and packaging (owner decisions 2026-10-14).
--
-- Every product has a base unit: the unit stock and stock movements are counted in. Its kind says
-- how quantities behave: 'count' (whole pieces), 'weight' (kilograms, 3 decimals), 'volume'
-- (litres, 3 decimals). Extra units (pack, box, carton, half kilo…) convert to the base unit with a
-- factor and may have their own barcodes and prices. Sale and purchase lines keep a snapshot of the
-- unit, factor, price and cost they were recorded with, so later configuration changes never alter
-- history. Existing lines are base-unit lines (factor 1).

ALTER TABLE products
  ADD COLUMN unit_kind text NOT NULL DEFAULT 'count' CHECK (unit_kind IN ('count', 'weight', 'volume'));

-- Classify existing products: weighed if the unit text says so, or if they were ever sold or stocked
-- in fractions (those must keep accepting fractional quantities).
UPDATE products p SET unit_kind = 'weight'
 WHERE lower(trim(COALESCE(p.unit, ''))) IN ('كجم', 'كيلو', 'كيلوجرام', 'كيلو جرام', 'كغ', 'kg', 'kilo', 'جم', 'جرام', 'g')
    OR COALESCE(p.stock_qty, 0) <> trunc(COALESCE(p.stock_qty, 0))
    OR EXISTS (SELECT 1 FROM sale_items si WHERE si.product_barcode = p.barcode AND si.quantity <> trunc(si.quantity));
UPDATE products p SET unit_kind = 'volume'
 WHERE unit_kind = 'count' AND lower(trim(COALESCE(p.unit, ''))) IN ('لتر', 'ليتر', 'l', 'liter', 'litre');

CREATE TABLE product_units (
  id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_barcode text NOT NULL REFERENCES products(barcode) ON UPDATE CASCADE,
  name            text NOT NULL CHECK (length(trim(name)) > 0),
  factor          numeric NOT NULL CHECK (factor > 0),    -- base units per one of this unit
  retail_price    numeric CHECK (retail_price >= 0),      -- NULL: base price × factor
  wholesale_price numeric CHECK (wholesale_price >= 0),
  sellable        boolean NOT NULL DEFAULT true,
  purchasable     boolean NOT NULL DEFAULT true,
  is_active       boolean NOT NULL DEFAULT true,
  created_at      timestamp NOT NULL DEFAULT LOCALTIMESTAMP(0),
  updated_at      timestamp
);
CREATE UNIQUE INDEX product_units_name_key ON product_units(product_barcode, lower(name)) WHERE is_active;

-- Extra barcodes: for the base unit (unit_id NULL) or for a packaging unit.
CREATE TABLE product_barcodes (
  barcode         text PRIMARY KEY CHECK (length(trim(barcode)) > 0),
  product_barcode text NOT NULL REFERENCES products(barcode) ON UPDATE CASCADE ON DELETE CASCADE,
  unit_id         integer REFERENCES product_units(id)
);
CREATE INDEX idx_product_barcodes_product ON product_barcodes(product_barcode);

-- A code identifies exactly one product unit: an extra barcode may not equal any product's main
-- barcode, and a new product's barcode may not equal an extra barcode.
CREATE FUNCTION hm_unique_scan_code() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_TABLE_NAME = 'product_barcodes' THEN
    IF EXISTS (SELECT 1 FROM products WHERE barcode = NEW.barcode) THEN
      RAISE EXCEPTION 'الباركود (%) مستخدم بالفعل لصنف آخر.', NEW.barcode USING ERRCODE = 'P0001';
    END IF;
  ELSIF EXISTS (SELECT 1 FROM product_barcodes WHERE barcode = NEW.barcode) THEN
    RAISE EXCEPTION 'الباركود (%) مستخدم بالفعل كباركود إضافي لصنف آخر.', NEW.barcode USING ERRCODE = 'P0001';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER product_barcodes_unique BEFORE INSERT OR UPDATE OF barcode ON product_barcodes
  FOR EACH ROW EXECUTE FUNCTION hm_unique_scan_code();
CREATE TRIGGER products_barcode_unique BEFORE INSERT OR UPDATE OF barcode ON products
  FOR EACH ROW EXECUTE FUNCTION hm_unique_scan_code();

-- Line snapshots. quantity, returned_qty, unit_price and cost_price stay in the line's unit;
-- base_qty = quantity × unit_factor is what moved in stock.
ALTER TABLE sale_items
  ADD COLUMN unit_id     integer REFERENCES product_units(id),
  ADD COLUMN unit_name   text,
  ADD COLUMN unit_factor numeric NOT NULL DEFAULT 1 CHECK (unit_factor > 0);

ALTER TABLE supplier_purchase_items
  ADD COLUMN unit_id     integer REFERENCES product_units(id),
  ADD COLUMN unit_name   text,
  ADD COLUMN unit_factor numeric NOT NULL DEFAULT 1 CHECK (unit_factor > 0);
