-- 0008 – Staff passwords and supervisor approvals (stage 4 phase 3, owner decisions 2026-10-14).
--
-- Passwords replace PIN-only login. Existing users keep their PIN for exactly one more sign-in:
-- username + current PIN, then they must choose a password and the PIN is erased. Nothing is
-- converted here, so this migration changes no existing value.
--
-- Approvals: a cashier's return needs a supervisor (and a reason); a shift closed with a cash
-- difference above EGP 50 needs a supervisor's acknowledgement. Every decision is kept – approvals,
-- refusals and failed attempts – and every return is recorded with its reason and approver.
-- User ids are stored without foreign keys (with the username as it was) so the record survives
-- later user changes.

ALTER TABLE users
  ADD COLUMN password_scrypt       text,                            -- scrypt$N$r$p$salt$hash
  ADD COLUMN must_change_password  boolean NOT NULL DEFAULT false,  -- temporary password set by an administrator or reset
  ADD COLUMN password_changed_at   timestamp,
  ADD COLUMN recovery_hash         text,                            -- one-time recovery code (super administrators)
  ADD COLUMN recovery_created_at   timestamp;

CREATE TABLE approvals (
  id                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  action             text NOT NULL CHECK (action IN ('sale_return', 'shift_difference')),
  decision           text NOT NULL CHECK (decision IN ('approved', 'refused', 'failed')),
  requested_by       integer,
  requested_username text,
  approver_id        integer,           -- NULL when the credentials did not match an account
  approver_username  text,              -- as typed
  self_approved      boolean NOT NULL DEFAULT false,  -- the requester holds the authority themselves
  subject_type       text NOT NULL,     -- 'sale', 'sale_item' or 'shift'
  subject_id         integer NOT NULL,
  amount             numeric(14, 2),
  reason             text,
  failure            text,              -- why a failed attempt failed (wrong password, no authority, …)
  terminal           text,
  created_at         timestamp NOT NULL DEFAULT LOCALTIMESTAMP(0)
);
CREATE INDEX idx_approvals_subject ON approvals (subject_type, subject_id);
CREATE INDEX idx_approvals_created ON approvals (created_at);

-- One row per return (item or whole invoice): who, why, how much, approved by whom.
CREATE TABLE sale_returns (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sale_id       integer NOT NULL REFERENCES sales(id),
  sale_item_id  integer REFERENCES sale_items(id) ON DELETE SET NULL,  -- NULL: the whole invoice
  quantity      numeric(14, 3),
  refund        numeric(14, 2) NOT NULL,
  reason        text,
  user_id       integer,
  username      text,
  approval_id   integer REFERENCES approvals(id),
  shift_id      integer,
  created_at    timestamp NOT NULL DEFAULT LOCALTIMESTAMP(0)
);
CREATE INDEX idx_sale_returns_sale ON sale_returns (sale_id);

ALTER TABLE shifts ADD COLUMN difference_approval_id integer REFERENCES approvals(id);
