-- Stage 4, phase 1: stock movement ledger, negative stock, purchase lines (owner decisions 2026-10-14).
--
-- products.stock_qty becomes a cached total of stock_movements:
--   * every stock change is an immutable movement row;
--   * a trigger on stock_movements updates products.stock_qty in the same statement;
--   * a guard trigger refuses any other change to products.stock_qty (K-37: no absolute overwrites).
-- Negative stock is allowed (the former prevent_negative_stock trigger is dropped).

DROP TRIGGER IF EXISTS prevent_negative_stock ON products;
DROP FUNCTION IF EXISTS hm_prevent_negative_stock();

CREATE TABLE stock_movements (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_barcode text NOT NULL REFERENCES products(barcode) ON UPDATE CASCADE,
  qty             numeric NOT NULL CHECK (qty <> 0),            -- signed, in the product's stock unit
  kind            text NOT NULL CHECK (kind IN ('opening', 'sale', 'return', 'purchase', 'adjustment', 'count', 'damaged', 'damaged_reversal')),
  unit_cost       numeric NOT NULL,                             -- cost per unit used for this movement
  balance_after   numeric NOT NULL,                             -- products.stock_qty right after it
  ref_type        text,                                         -- sale, sale_item, purchase, damaged, product
  ref_id          integer,
  reason          text,
  user_id         integer,
  created_at      timestamp NOT NULL DEFAULT LOCALTIMESTAMP(0)
);
CREATE INDEX idx_stock_movements_product ON stock_movements(product_barcode, id);
CREATE INDEX idx_stock_movements_ref ON stock_movements(ref_type, ref_id);

CREATE TABLE supplier_purchase_items (
  id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  purchase_id     integer NOT NULL REFERENCES supplier_purchases(id),
  product_barcode text NOT NULL REFERENCES products(barcode) ON UPDATE CASCADE,
  qty             numeric NOT NULL CHECK (qty > 0),
  unit_cost       numeric NOT NULL CHECK (unit_cost >= 0),
  line_total      numeric NOT NULL
);
CREATE INDEX idx_supplier_purchase_items_purchase ON supplier_purchase_items(purchase_id);

-- Movement → stock. hm.ledger_rebuild = on lets opening balances and administrative rebuilds write
-- rows whose effect is already in products.stock_qty.
CREATE FUNCTION hm_apply_stock_movement() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
  cur  numeric;
  cost numeric;
BEGIN
  IF current_setting('hm.ledger_rebuild', true) = 'on' THEN
    RETURN NEW;
  END IF;
  SELECT COALESCE(stock_qty, 0), COALESCE(cost_price, 0) INTO cur, cost
    FROM products WHERE barcode = NEW.product_barcode FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'الصنف (%) غير موجود.', NEW.product_barcode USING ERRCODE = 'P0001';
  END IF;
  PERFORM set_config('hm.stock_post', 'on', true);
  UPDATE products SET stock_qty = cur + NEW.qty WHERE barcode = NEW.product_barcode;
  PERFORM set_config('hm.stock_post', 'off', true);
  NEW.balance_after := cur + NEW.qty;
  IF NEW.unit_cost IS NULL THEN
    NEW.unit_cost := cost;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER apply_stock_movement BEFORE INSERT ON stock_movements
  FOR EACH ROW EXECUTE FUNCTION hm_apply_stock_movement();

CREATE FUNCTION hm_stock_movements_immutable() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF current_setting('hm.ledger_rebuild', true) = 'on' THEN
    RETURN COALESCE(NEW, OLD);
  END IF;
  RAISE EXCEPTION 'حركات المخزون لا تُعدَّل ولا تُحذف؛ سجّل حركة تصحيح بدلاً من ذلك.' USING ERRCODE = 'P0001';
END $$;
CREATE TRIGGER stock_movements_immutable BEFORE UPDATE OR DELETE ON stock_movements
  FOR EACH ROW EXECUTE FUNCTION hm_stock_movements_immutable();

CREATE FUNCTION hm_guard_stock() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF current_setting('hm.stock_post', true) = 'on' OR current_setting('hm.ledger_rebuild', true) = 'on' THEN
    RETURN NEW;
  END IF;
  IF TG_OP = 'INSERT' AND COALESCE(NEW.stock_qty, 0) <> 0 THEN
    RAISE EXCEPTION 'رصيد الصنف يُسجَّل كحركة مخزون، وليس كقيمة مباشرة.' USING ERRCODE = 'P0001';
  END IF;
  IF TG_OP = 'UPDATE' AND NEW.stock_qty IS DISTINCT FROM OLD.stock_qty THEN
    RAISE EXCEPTION 'لا يمكن تعديل رصيد الصنف مباشرة؛ استخدم حركة مخزون (جرد أو استلام أو تسوية).' USING ERRCODE = 'P0001';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER guard_stock BEFORE INSERT OR UPDATE OF stock_qty ON products
  FOR EACH ROW EXECUTE FUNCTION hm_guard_stock();

-- Opening balances: one movement per product whose stock is not yet explained by its movements.
-- Used here, after a legacy import, and after a data reset. Returns the number of rows written.
CREATE FUNCTION hm_post_opening_balances(note text) RETURNS integer LANGUAGE plpgsql AS $$
DECLARE
  n integer;
BEGIN
  PERFORM set_config('hm.ledger_rebuild', 'on', true);
  INSERT INTO stock_movements (product_barcode, qty, kind, unit_cost, balance_after, reason)
  SELECT p.barcode, COALESCE(p.stock_qty, 0) - COALESCE(m.s, 0), 'opening', COALESCE(p.cost_price, 0),
         COALESCE(p.stock_qty, 0), note
    FROM products p
    LEFT JOIN (SELECT product_barcode, SUM(qty) AS s FROM stock_movements GROUP BY product_barcode) m
      ON m.product_barcode = p.barcode
   WHERE COALESCE(p.stock_qty, 0) - COALESCE(m.s, 0) <> 0
   ORDER BY p.barcode;
  GET DIAGNOSTICS n = ROW_COUNT;
  PERFORM set_config('hm.ledger_rebuild', 'off', true);
  RETURN n;
END $$;

SELECT hm_post_opening_balances('رصيد افتتاحي عند تفعيل سجل حركة المخزون');
