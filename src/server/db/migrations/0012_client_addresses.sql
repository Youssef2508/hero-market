-- 0012 – Customers can have up to three delivery addresses (owner request, 1.4.0).
--
-- Addresses are optional. Each has a label (home, work, other), the address itself, optional
-- details (floor, apartment, landmark) and at most one is the customer's default. The limit of
-- three is enforced here, not only in the screens. A customer's existing address becomes their
-- default address; clients.address keeps mirroring the default (the service updates it), so older
-- screens, reports and receipts keep working. Invoices keep a snapshot of the delivery address.

CREATE TABLE client_addresses (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_id   integer NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
  label       text NOT NULL DEFAULT 'other' CHECK (label IN ('home', 'work', 'other')),
  address     text NOT NULL CHECK (length(btrim(address)) BETWEEN 1 AND 300),
  details     text CHECK (details IS NULL OR length(details) <= 200),
  is_default  boolean NOT NULL DEFAULT false,
  created_at  timestamp NOT NULL DEFAULT LOCALTIMESTAMP(0),
  updated_at  timestamp
);
CREATE INDEX idx_client_addresses_client ON client_addresses (client_id);
CREATE UNIQUE INDEX client_addresses_one_default ON client_addresses (client_id) WHERE is_default;

-- At most three per customer, also for simultaneous requests (the customer row is locked).
CREATE FUNCTION hm_client_addresses_max() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF current_setting('hm.bulk_load', true) = 'on' THEN
    RETURN NEW;
  END IF;
  PERFORM 1 FROM clients WHERE id = NEW.client_id FOR UPDATE;
  IF (SELECT count(*) FROM client_addresses WHERE client_id = NEW.client_id AND id <> NEW.id) >= 3 THEN
    RAISE EXCEPTION 'يمكن تسجيل ثلاثة عناوين على الأكثر لكل عميل.' USING ERRCODE = 'P0001';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER client_addresses_max BEFORE INSERT OR UPDATE OF client_id ON client_addresses
  FOR EACH ROW EXECUTE FUNCTION hm_client_addresses_max();

-- Synchronised with the owner's cloud like the other customer data (migration 0009). Created
-- before the copy below, so a store already linked to the cloud sends the copied addresses too.
INSERT INTO sync_tables (table_name, key_column) VALUES ('client_addresses', 'id');
CREATE TRIGGER zz_sync_capture AFTER INSERT OR UPDATE OR DELETE ON client_addresses
  FOR EACH ROW EXECUTE FUNCTION hm_sync_capture('id');

-- Existing customers: their address (if any) becomes the default address.
INSERT INTO client_addresses (client_id, label, address, is_default, created_at)
SELECT id, 'other', btrim(address), true, COALESCE(created_at, LOCALTIMESTAMP(0))
  FROM clients
 WHERE length(btrim(COALESCE(address, ''))) BETWEEN 1 AND 300;

-- Delivery on the invoice: whether it was a delivery and the address it went to (a snapshot: later
-- edits of the customer's addresses never change history).
ALTER TABLE sales
  ADD COLUMN is_delivery      boolean NOT NULL DEFAULT false,
  ADD COLUMN delivery_address text;
