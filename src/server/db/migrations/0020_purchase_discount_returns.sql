-- 0020 – Purchase invoice discount and purchase returns (owner, 2026-10-22, D-066). Schema only;
-- no stored value changes.
--
--   1. Invoice-level discount (SUP-02): a purchase records its lines' value (gross), an optional
--      discount, and the net it is owed for (total_amount, as before). Lines keep their prices, so
--      product costs and the moving average are unchanged; the discount is a purchase gain in profit.
--      Existing purchases: gross NULL means "no discount" (gross = total_amount).
--   2. Purchase returns: quantities of a recorded purchase sent back to the supplier, in parts,
--      once per request. Stock leaves at the line's cost; the supplier is credited the line value
--      × net ÷ gross; money given back is recorded only when received, by its method.
--
-- Rollback: restore the verified copy taken by the installer before this migration (Case B).

ALTER TABLE supplier_purchases
  ADD COLUMN gross_amount numeric CHECK (gross_amount IS NULL OR gross_amount >= 0),
  ADD COLUMN discount     numeric NOT NULL DEFAULT 0 CHECK (discount >= 0),
  ADD CONSTRAINT supplier_purchases_net_check
    CHECK (discount = 0 OR (gross_amount IS NOT NULL AND discount <= gross_amount
                            AND total_amount = gross_amount - discount));

CREATE TABLE supplier_purchase_returns (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  purchase_id   integer NOT NULL REFERENCES supplier_purchases(id),
  supplier_id   integer NOT NULL REFERENCES suppliers(id),
  -- Value of the returned lines at their purchase prices, and what the supplier is credited.
  gross_value   numeric NOT NULL CHECK (gross_value > 0),
  credit_value  numeric NOT NULL CHECK (credit_value >= 0 AND credit_value <= gross_value),
  -- Money the supplier gave back now (0: owed by the supplier until paid), by its method.
  refund_amount numeric NOT NULL DEFAULT 0 CHECK (refund_amount >= 0 AND refund_amount <= credit_value),
  refund_method text CHECK (refund_method IS NULL OR refund_method IN ('cash', 'visa', 'wallet', 'instapay')),
  destination   text CHECK (destination IS NULL OR destination IN ('shift', 'treasury')),
  shift_id      integer REFERENCES shifts(id),
  reason        text CHECK (reason IS NULL OR length(reason) <= 300),
  client_ref    text NOT NULL UNIQUE CHECK (length(client_ref) <= 120),
  created_by    integer REFERENCES users(id),
  created_at    timestamp NOT NULL DEFAULT LOCALTIMESTAMP(0),
  CHECK (refund_amount = 0 OR (refund_method IS NOT NULL AND destination IS NOT NULL)),
  CHECK (destination IS DISTINCT FROM 'shift' OR shift_id IS NOT NULL)
);
CREATE INDEX idx_purchase_returns_purchase ON supplier_purchase_returns (purchase_id);

CREATE TABLE supplier_purchase_return_items (
  id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  return_id        integer NOT NULL REFERENCES supplier_purchase_returns(id),
  purchase_item_id integer NOT NULL REFERENCES supplier_purchase_items(id),
  product_barcode  text NOT NULL REFERENCES products(barcode) ON UPDATE CASCADE,
  -- In the purchase line's unit (boxes when bought in boxes), and in the base unit for stock.
  qty              numeric NOT NULL CHECK (qty > 0),
  base_qty         numeric NOT NULL CHECK (base_qty > 0),
  unit_cost        numeric NOT NULL CHECK (unit_cost >= 0),
  line_value       numeric NOT NULL CHECK (line_value >= 0)
);
CREATE INDEX idx_purchase_return_items_item ON supplier_purchase_return_items (purchase_item_id);

ALTER TABLE stock_movements
  DROP CONSTRAINT stock_movements_kind_check,
  ADD CONSTRAINT stock_movements_kind_check
    CHECK (kind IN ('opening', 'sale', 'return', 'purchase', 'purchase_return', 'adjustment', 'count',
                    'damaged', 'damaged_reversal'));

INSERT INTO sync_tables (table_name, key_column) VALUES
