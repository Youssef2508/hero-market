-- 0040 – Purchase invoice corrections (D-112) and the password rule by internet access (D-113).

-- ── Passwords (D-113) ────────────────────────────────────────────────────────────────────────
-- Whether the user's current password meets the strong rule that signing in through the internet
-- needs. Only a hash is kept, so the answer is recorded when a password is set. Every password set
-- before this version was checked against the strong rule (D-058, D-105): true for them all. A user
-- without a password (PIN only) cannot sign in through the internet either way.
ALTER TABLE users ADD COLUMN password_strong boolean NOT NULL DEFAULT true;

-- ── Purchase corrections (D-112) ─────────────────────────────────────────────────────────────
-- The invoice's own revision number: a correction names the revision it was prepared on, so two
-- corrections of the same invoice never overwrite each other, and a stale screen cannot save.
ALTER TABLE supplier_purchases ADD COLUMN revision integer NOT NULL DEFAULT 0;

-- One row per correction: what the invoice was and became, and everything the correction moved.
-- The invoice and its lines always show the corrected values; this is their history.
CREATE TABLE supplier_purchase_revisions (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  purchase_id   integer NOT NULL REFERENCES supplier_purchases(id) ON DELETE CASCADE,
  supplier_id   integer NOT NULL REFERENCES suppliers(id),
  revision      integer NOT NULL,
  reason        text,
  old_total     numeric(14, 2) NOT NULL,
  new_total     numeric(14, 2) NOT NULL,
  delta         numeric(14, 2) NOT NULL,     -- new − old: what the supplier is owed in addition
  old_discount  numeric(14, 2) NOT NULL DEFAULT 0,
  new_discount  numeric(14, 2) NOT NULL DEFAULT 0,
  paid          numeric(14, 2) NOT NULL,     -- paid with the invoice (unchanged by a correction)
  old_lines     jsonb NOT NULL,
  new_lines     jsonb NOT NULL,
  stock_changes jsonb NOT NULL,              -- per product: base quantity and the stock after it
  cost_changes  jsonb NOT NULL,              -- per product: purchase price before and after
  sold_since    jsonb NOT NULL,              -- per product: units sold since the invoice (information)
  old_ref       text,
  new_ref       text,
  old_notes     text,
  new_notes     text,
  client_ref    text NOT NULL UNIQUE,
  created_by    integer REFERENCES users(id),
  created_at    timestamp NOT NULL DEFAULT LOCALTIMESTAMP(0),
  UNIQUE (purchase_id, revision)
);
CREATE INDEX supplier_purchase_revisions_purchase ON supplier_purchase_revisions (purchase_id);

INSERT INTO sync_tables (table_name, key_column) VALUES ('supplier_purchase_revisions', 'id');
CREATE TRIGGER zz_sync_capture AFTER INSERT OR UPDATE OR DELETE ON supplier_purchase_revisions
  FOR EACH ROW EXECUTE FUNCTION hm_sync_capture('id');

-- A correction's stock movement: the difference between a line as it was and as it is now,
-- posted on top of the history (the original receipt stays as it was).
ALTER TABLE stock_movements
  DROP CONSTRAINT stock_movements_kind_check,
  ADD CONSTRAINT stock_movements_kind_check
    CHECK (kind IN ('opening', 'sale', 'return', 'purchase', 'purchase_return', 'purchase_correction',
                    'adjustment', 'count', 'damaged', 'damaged_reversal'));

-- Purchase invoices by date, for the list of every supplier's invoices (D-112).
CREATE INDEX IF NOT EXISTS supplier_purchases_time ON supplier_purchases (timestamp DESC, id DESC);
