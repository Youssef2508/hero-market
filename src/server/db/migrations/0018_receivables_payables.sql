-- 0018 – Preliminary supplier invoices, per-method treasury, movement kinds (owner, 2026-10-21,
-- D-064). Adds; changes no stored amount.
--
--   1. treasury_ledger.method: the treasury holds the business's funds by payment method. Every
--      existing row was cash (the opening float, the counted cash at close, deposits, cash
--      expenses), which is the default.
--   2. safe_ledger.kind: what each shift money movement is (a collection is never a sale, a
--      supplier settlement is not an invoice payment). Filled from the texts the program has always
--      written (the same texts the drawer formula reads). safe_ledger.client_ref: the request that
--      wrote it, so a retried payment is recorded once.
--   3. supplier_pending_invoices: a supplier invoice recorded before its lines are known (its total,
--      what was paid and how). It moves money and the supplier's payable only; converting it into
--      a detailed purchase moves stock and cost, never the payment again.
--
-- Classification: schema + data (backfill of the new kind column from existing rows).
-- Rollback: restore the verified copy taken by the installer before this migration (Case B).

ALTER TABLE treasury_ledger
  ADD COLUMN method text NOT NULL DEFAULT 'cash'
    CHECK (method IN ('cash', 'visa', 'wallet', 'instapay'));
CREATE INDEX idx_treasury_method ON treasury_ledger (method, id);

ALTER TABLE safe_ledger
  ADD COLUMN kind text NOT NULL DEFAULT 'other'
    CHECK (kind IN ('sale_upfront', 'kept_change', 'customer_payment', 'supplier_payment',
                    'supplier_settlement', 'expense', 'refund', 'other')),
  ADD COLUMN client_ref text UNIQUE CHECK (client_ref IS NULL OR length(client_ref) <= 120);

-- Backfill of the new column on rows of closed shifts too (bookkeeping, no amount changes).
SELECT set_config('hm.bulk_load', 'on', true);
UPDATE safe_ledger SET kind = CASE
    WHEN description LIKE 'مرتجع%' OR description LIKE 'إرجاع%' THEN 'refund'
    WHEN description LIKE 'دفعة لمورد%' THEN 'supplier_payment'
    WHEN description LIKE 'سداد دين مورد%' THEN 'supplier_settlement'
    WHEN description LIKE 'سداد دين العميل%' THEN 'customer_payment'
    WHEN description LIKE 'مقدم نقدي بيع دفع جزئي%' THEN 'sale_upfront'
    WHEN description LIKE 'باقي محفوظ%' THEN 'kept_change'
    WHEN description LIKE 'مصروفات%' THEN 'expense'
    ELSE 'other' END;
SELECT set_config('hm.bulk_load', 'off', true);

CREATE TABLE supplier_pending_invoices (
  id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  supplier_id    integer NOT NULL REFERENCES suppliers(id),
  invoice_ref    text CHECK (invoice_ref IS NULL OR length(invoice_ref) <= 80),
  total          numeric(14, 2) NOT NULL CHECK (total > 0),
  paid           numeric(14, 2) NOT NULL DEFAULT 0 CHECK (paid >= 0 AND paid <= total),
  payment_mode   text NOT NULL CHECK (payment_mode IN ('cash', 'credit', 'partial')),
  method         text CHECK (method IS NULL OR method IN ('cash', 'visa', 'wallet', 'instapay')),
  destination    text CHECK (destination IS NULL OR destination IN ('shift', 'treasury')),
  shift_id       integer REFERENCES shifts(id),
  ledger_id      integer,
  treasury_entry_id integer REFERENCES treasury_ledger(id),
  notes          text CHECK (notes IS NULL OR length(notes) <= 500),
  status         text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'converted')),
  purchase_id    integer REFERENCES supplier_purchases(id),
  final_total    numeric(14, 2),
  difference     numeric(14, 2),
  created_by     integer REFERENCES users(id),
  created_at     timestamp NOT NULL DEFAULT LOCALTIMESTAMP(0),
  converted_by   integer REFERENCES users(id),
  converted_at   timestamp,
  client_ref     text UNIQUE CHECK (client_ref IS NULL OR length(client_ref) <= 120),
  convert_ref    text UNIQUE CHECK (convert_ref IS NULL OR length(convert_ref) <= 120),
  -- cash: paid in full; credit: nothing paid; partial: something, not all.
  CHECK ((payment_mode = 'cash' AND paid = total) OR (payment_mode = 'credit' AND paid = 0)
         OR (payment_mode = 'partial' AND paid > 0 AND paid < total)),
  CHECK (paid = 0 OR (method IS NOT NULL AND destination IS NOT NULL)),
  CHECK (status = 'pending' OR (purchase_id IS NOT NULL AND converted_at IS NOT NULL))
);
CREATE INDEX idx_pending_invoices_status ON supplier_pending_invoices (status, id);

INSERT INTO sync_tables (table_name, key_column) VALUES ('supplier_pending_invoices', 'id');
CREATE TRIGGER zz_sync_capture AFTER INSERT OR UPDATE OR DELETE ON supplier_pending_invoices
  FOR EACH ROW EXECUTE FUNCTION hm_sync_capture('id');
